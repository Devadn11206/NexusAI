"""NEXUS AI - Multi-Format Generator & File Converter.
Generates styled Word (.docx), Excel (.xlsx), and PowerPoint (.pptx) deliverables.
Provides seamless format conversions (e.g. .md -> .docx, .docx -> .txt, .csv -> .xlsx).
"""

from __future__ import annotations

import csv
import datetime
from pathlib import Path
from typing import Any, Dict, List, Optional, Union

import docx
from docx.shared import Inches, Pt, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.enum.table import WD_TABLE_ALIGNMENT

import openpyxl
from openpyxl.styles import Font, PatternFill, Alignment, Border, Side
from openpyxl.utils import get_column_letter

import pptx
from pptx.util import Inches as PptInches, Pt as PptPt
from pptx.dml.color import RGBColor as PptRGBColor

DEFAULT_OUTPUT_DIR = Path("./workspace/artifacts")


def generate_word_report(
    title: str,
    sections: List[Dict[str, Any]],
    output_path: Optional[str] = None,
    author: str = "NEXUS AI Intelligence",
) -> str:
    """Generate an enterprise-styled Word report (.docx) with cover styling, headings, and tables."""
    doc = docx.Document()

    # Document Title / Header
    title_p = doc.add_paragraph()
    title_p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    title_run = title_p.add_run(title)
    title_run.font.name = "Segoe UI"
    title_run.font.size = Pt(24)
    title_run.font.bold = True
    title_run.font.color.rgb = RGBColor(16, 44, 87)

    # Sub-header / Metadata
    meta_p = doc.add_paragraph()
    meta_p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    meta_run = meta_p.add_run(f"Generated by {author} | {datetime.datetime.now().strftime('%B %d, %Y')}")
    meta_run.font.name = "Segoe UI"
    meta_run.font.size = Pt(10)
    meta_run.font.italic = True
    meta_run.font.color.rgb = RGBColor(100, 116, 139)

    doc.add_paragraph()  # Spacer

    # Add Sections
    for sec in sections:
        heading = sec.get("heading", "Section")
        body = sec.get("body", "")
        table_data = sec.get("table")  # List of dicts or list of lists

        h = doc.add_heading(level=1)
        h_run = h.add_run(heading)
        h_run.font.name = "Segoe UI"
        h_run.font.size = Pt(16)
        h_run.font.color.rgb = RGBColor(30, 58, 138)

        if body:
            p = doc.add_paragraph()
            p_run = p.add_run(body)
            p_run.font.name = "Segoe UI"
            p_run.font.size = Pt(11)

        # Optional Table in section
        if table_data and isinstance(table_data, list) and len(table_data) > 0:
            if isinstance(table_data[0], dict):
                headers = list(table_data[0].keys())
                rows = [[str(item.get(k, "")) for k in headers] for item in table_data]
            else:
                headers = [str(c) for c in table_data[0]]
                rows = [[str(c) for c in r] for r in table_data[1:]]

            tbl = doc.add_table(rows=len(rows) + 1, cols=len(headers))
            tbl.alignment = WD_TABLE_ALIGNMENT.CENTER
            tbl.style = "Table Grid"

            # Header row styling
            hdr_cells = tbl.rows[0].cells
            for col_idx, h_text in enumerate(headers):
                cell = hdr_cells[col_idx]
                cell.text = h_text
                for paragraph in cell.paragraphs:
                    for run in paragraph.runs:
                        run.font.name = "Segoe UI"
                        run.font.bold = True
                        run.font.size = Pt(10)
                        run.font.color.rgb = RGBColor(255, 255, 255)

            # Data rows
            for row_idx, r_data in enumerate(rows):
                row_cells = tbl.rows[row_idx + 1].cells
                for col_idx, val in enumerate(r_data):
                    cell = row_cells[col_idx]
                    cell.text = val
                    for paragraph in cell.paragraphs:
                        for run in paragraph.runs:
                            run.font.name = "Segoe UI"
                            run.font.size = Pt(9.5)

            doc.add_paragraph()

    # Determine save path
    if not output_path:
        DEFAULT_OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
        safe_name = "".join(c for c in title if c.isalnum() or c in (" ", "_", "-")).rstrip()
        filename = f"{safe_name.replace(' ', '_')}_{datetime.datetime.now().strftime('%Y%m%d_%H%M%S')}.docx"
        output_path = str((DEFAULT_OUTPUT_DIR / filename).resolve())

    doc.save(output_path)
    return str(Path(output_path).resolve())


def generate_excel_workbook(
    sheet_data: Dict[str, List[Dict[str, Any]]],
    output_path: Optional[str] = None,
    workbook_title: str = "NEXUS AI Report",
) -> str:
    """Generate an Excel workbook with styled headers, alternating rows, borders, and auto-adjusted widths."""
    wb = openpyxl.Workbook()
    # Remove default sheet
    default_sheet = wb.active
    wb.remove(default_sheet)

    # Styles
    header_fill = PatternFill(start_color="1E3A8A", end_color="1E3A8A", fill_type="solid")
    header_font = Font(name="Segoe UI", size=11, bold=True, color="FFFFFF")
    zebra_fill = PatternFill(start_color="F1F5F9", end_color="F1F5F9", fill_type="solid")
    regular_font = Font(name="Segoe UI", size=10)
    thin_border = Border(
        left=Side(style="thin", color="CBD5E1"),
        right=Side(style="thin", color="CBD5E1"),
        top=Side(style="thin", color="CBD5E1"),
        bottom=Side(style="thin", color="CBD5E1"),
    )

    for sheet_name, rows in sheet_data.items():
        clean_sheet_name = sheet_name[:31]  # Excel 31-char limit
        ws = wb.create_sheet(title=clean_sheet_name)

        if not rows:
            ws.append(["No data"])
            continue

        headers = list(rows[0].keys())
        ws.append(headers)

        for col_num in range(1, len(headers) + 1):
            cell = ws.cell(row=1, column=col_num)
            cell.fill = header_fill
            cell.font = header_font
            cell.alignment = Alignment(horizontal="center", vertical="center")
            cell.border = thin_border

        for r_idx, row_dict in enumerate(rows, start=2):
            row_values = [row_dict.get(h, "") for h in headers]
            ws.append(row_values)
            is_even = (r_idx % 2 == 0)
            for c_idx in range(1, len(headers) + 1):
                cell = ws.cell(row=r_idx, column=c_idx)
                cell.font = regular_font
                cell.border = thin_border
                if is_even:
                    cell.fill = zebra_fill

        # Auto-adjust column widths
        for col in ws.columns:
            max_len = 0
            col_letter = get_column_letter(col[0].column)
            for cell in col:
                val = str(cell.value or "")
                if len(val) > max_len:
                    max_len = len(val)
            ws.column_dimensions[col_letter].width = min(max(max_len + 3, 12), 50)

    if not output_path:
        DEFAULT_OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
        safe_name = "".join(c for c in workbook_title if c.isalnum() or c in (" ", "_", "-")).rstrip()
        filename = f"{safe_name.replace(' ', '_')}_{datetime.datetime.now().strftime('%Y%m%d_%H%M%S')}.xlsx"
        output_path = str((DEFAULT_OUTPUT_DIR / filename).resolve())

    wb.save(output_path)
    return str(Path(output_path).resolve())


def generate_powerpoint_deck(
    deck_title: str,
    slides: List[Dict[str, Any]],
    output_path: Optional[str] = None,
    subtitle: str = "Prepared by NEXUS AI Intelligence",
) -> str:
    """Generate a sleek 16:9 presentation deck (.pptx) with structured titles and bullet points."""
    prs = pptx.Presentation()
    # 16:9 Widescreen dimensions
    prs.slide_width = PptInches(13.333)
    prs.slide_height = PptInches(7.5)

    blank_layout = prs.slide_layouts[6]

    # Slide 1: Title Slide
    title_slide = prs.slides.add_slide(blank_layout)
    tx_box = title_slide.shapes.add_textbox(PptInches(1.5), PptInches(2.5), PptInches(10.3), PptInches(2.5))
    tf = tx_box.text_frame
    tf.word_wrap = True

    p_title = tf.paragraphs[0]
    p_title.text = deck_title
    p_title.font.name = "Segoe UI"
    p_title.font.size = PptPt(44)
    p_title.font.bold = True
    p_title.font.color.rgb = PptRGBColor(16, 44, 87)

    p_sub = tf.add_paragraph()
    p_sub.text = subtitle
    p_sub.font.name = "Segoe UI"
    p_sub.font.size = PptPt(20)
    p_sub.font.color.rgb = PptRGBColor(100, 116, 139)

    # Content Slides
    for slide_info in slides:
        s_title = slide_info.get("title", "Overview")
        bullets = slide_info.get("bullets", [])

        s = prs.slides.add_slide(blank_layout)

        # Slide Title Box
        title_box = s.shapes.add_textbox(PptInches(1.0), PptInches(0.8), PptInches(11.3), PptInches(1.2))
        tf_s = title_box.text_frame
        p_st = tf_s.paragraphs[0]
        p_st.text = s_title
        p_st.font.name = "Segoe UI"
        p_st.font.size = PptPt(30)
        p_st.font.bold = True
        p_st.font.color.rgb = PptRGBColor(30, 58, 138)

        # Bullets Box
        bullet_box = s.shapes.add_textbox(PptInches(1.0), PptInches(2.2), PptInches(11.3), PptInches(4.5))
        tf_b = bullet_box.text_frame
        tf_b.word_wrap = True

        for idx, bullet_text in enumerate(bullets):
            p = tf_b.paragraphs[0] if idx == 0 else tf_b.add_paragraph()
            p.text = f"•  {bullet_text}"
            p.font.name = "Segoe UI"
            p.font.size = PptPt(18)
            p.font.color.rgb = PptRGBColor(30, 41, 59)
            p.space_after = PptPt(14)

    if not output_path:
        DEFAULT_OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
        safe_name = "".join(c for c in deck_title if c.isalnum() or c in (" ", "_", "-")).rstrip()
        filename = f"{safe_name.replace(' ', '_')}_{datetime.datetime.now().strftime('%Y%m%d_%H%M%S')}.pptx"
        output_path = str((DEFAULT_OUTPUT_DIR / filename).resolve())

    prs.save(output_path)
    return str(Path(output_path).resolve())


def create_meeting_notes(
    meeting_title: str,
    attendees: List[str],
    agenda: List[str],
    action_items: List[Dict[str, str]],
    discussion_summary: str,
    output_path: Optional[str] = None,
) -> str:
    """Generate structured meeting minutes document (.docx) with attendees, agenda, and action items table."""
    sections = [
        {
            "heading": "Meeting Details & Attendees",
            "body": f"Attendees: {', '.join(attendees) if attendees else 'All hands'}",
        },
        {
            "heading": "Agenda",
            "body": "\n".join(f"{idx+1}. {item}" for idx, item in enumerate(agenda)),
        },
        {
            "heading": "Key Discussion Summary",
            "body": discussion_summary,
        },
        {
            "heading": "Action Items & Ownership",
            "body": "The following deliverables and accountability assignments were agreed upon:",
            "table": action_items,
        },
    ]

    return generate_word_report(
        title=f"Meeting Minutes: {meeting_title}",
        sections=sections,
        output_path=output_path,
        author="NEXUS Meeting Intelligence",
    )


def convert_document_format(source_file: str, target_format: str, output_path: Optional[str] = None) -> str:
    """Convert files between formats (e.g. .md -> .docx, .txt -> .docx, .csv -> .xlsx)."""
    src = Path(source_file)
    if not src.exists():
        raise FileNotFoundError(f"Source file not found: {source_file}")

    target_ext = target_format.lower()
    if not target_ext.startswith("."):
        target_ext = f".{target_ext}"

    DEFAULT_OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    if not output_path:
        output_path = str((DEFAULT_OUTPUT_DIR / f"{src.stem}{target_ext}").resolve())

    src_ext = src.suffix.lower()

    if target_ext == ".docx":
        # Convert Markdown or TXT to DOCX
        with open(src, "r", encoding="utf-8", errors="replace") as f:
            content = f.read()

        doc = docx.Document()
        doc.add_heading(src.stem.replace("_", " ").title(), level=0)
        for line in content.splitlines():
            line_str = line.strip()
            if line_str.startswith("# "):
                doc.add_heading(line_str[2:], level=1)
            elif line_str.startswith("## "):
                doc.add_heading(line_str[3:], level=2)
            elif line_str.startswith("### "):
                doc.add_heading(line_str[4:], level=3)
            elif line_str.startswith("- ") or line_str.startswith("* "):
                doc.add_paragraph(line_str[2:], style="List Bullet")
            elif line_str:
                doc.add_paragraph(line_str)
        doc.save(output_path)

    elif target_ext in [".xlsx", ".xls"]:
        if src_ext in [".csv", ".tsv"]:
            wb = openpyxl.Workbook()
            ws = wb.active
            delimiter = "\t" if src_ext == ".tsv" else ","
            with open(src, "r", encoding="utf-8", errors="replace") as f:
                reader = csv.reader(f, delimiter=delimiter)
                for row in reader:
                    ws.append(row)
            wb.save(output_path)
        else:
            raise ValueError(f"Direct conversion from {src_ext} to {target_ext} not supported")

    elif target_ext == ".txt":
        from app.documents.parser_extractor import parse_document
        parsed = parse_document(str(src))
        with open(output_path, "w", encoding="utf-8") as f:
            f.write(parsed["text"])

    else:
        raise ValueError(f"Conversion to target format {target_ext} is not supported.")

    return str(Path(output_path).resolve())

