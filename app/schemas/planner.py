import enum
from typing import List, Dict, Any, Optional
from pydantic import BaseModel, Field


class IntentCategory(str, enum.Enum):
    BROWSER = "BROWSER"
    FILESYSTEM = "FILESYSTEM"
    DOCUMENTS = "DOCUMENTS"
    DEVELOPER = "DEVELOPER"
    COMPUTER = "COMPUTER"
    HYBRID = "HYBRID"


class TargetAgent(str, enum.Enum):
    BrowserAgent = "BrowserAgent"
    FileAgent = "FileAgent"
    DeveloperAgent = "DeveloperAgent"
    DocumentAgent = "DocumentAgent"
    ComputerAgent = "ComputerAgent"
    SupervisorAgent = "SupervisorAgent"


class TaskStep(BaseModel):
    """Atomic step in the Directed Acyclic Graph (DAG) execution plan."""
    step_id: str = Field(
        ...,
        description="Unique identifier for the step (e.g. 'step_1', 'step_2')."
    )
    description: str = Field(
        ...,
        description="Actionable explanation of what this step will execute."
    )
    target_agent: TargetAgent = Field(
        ...,
        description="Assigned specialist agent (e.g., BrowserAgent, FileAgent, DeveloperAgent)."
    )
    tool_name: str = Field(
        ...,
        description="The MCP or local tool required (e.g., 'web_search', 'create_excel', 'execute_bash')."
    )
    tool_params: Dict[str, Any] = Field(
        default_factory=dict,
        description="Structured key-value arguments supplied to the tool."
    )
    depends_on: List[str] = Field(
        default_factory=list,
        description="List of step_ids that must finish before this step runs."
    )
    expected_output: str = Field(
        ...,
        description="Expected artifact or data produced by this step."
    )


class TaskGraph(BaseModel):
    """
    Complete synthesized task plan generated by the Task Planner.
    Includes classification, DAG steps, and ambiguity clarification flags.
    """
    intent_category: IntentCategory = Field(
        ...,
        description="Primary domain classification (BROWSER, FILESYSTEM, DOCUMENTS, DEVELOPER, COMPUTER, HYBRID)."
    )
    summary: str = Field(
        ...,
        description="A concise executive overview of the plan."
    )
    requires_clarification: bool = Field(
        default=False,
        description="True if critical information or ambiguous parameters prevent execution."
    )
    clarification_prompt: Optional[str] = Field(
        default=None,
        description="Clear questions to ask the user if requires_clarification is True."
    )
    steps: List[TaskStep] = Field(
        default_factory=list,
        description="List of ordered, dependent DAG steps."
    )

